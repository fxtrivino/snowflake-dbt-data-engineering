WITH customer_totals AS (
    SELECT
        SUM(TOTAL_ORDERS) AS TOTAL_ORDERS,
        SUM(CONFIRMED_SALES_AMOUNT) AS SALES,
        SUM(PAID_AMOUNT) AS PAID,
        SUM(PENDING_PAYMENT_AMOUNT) AS PENDING,
        SUM(OUTSTANDING_AMOUNT) AS OUTSTANDING
    FROM {{ ref('customer_sales') }}
),

daily_totals AS (
    SELECT
        SUM(TOTAL_ORDERS) AS TOTAL_ORDERS,
        SUM(CONFIRMED_SALES_AMOUNT) AS SALES,
        SUM(PAID_AMOUNT) AS PAID,
        SUM(PENDING_PAYMENT_AMOUNT) AS PENDING,
        SUM(OUTSTANDING_AMOUNT) AS OUTSTANDING
    FROM {{ ref('sales_daily') }}
)

SELECT *
FROM customer_totals c
CROSS JOIN daily_totals d
WHERE c.TOTAL_ORDERS <> d.TOTAL_ORDERS
   OR c.SALES <> d.SALES
   OR c.PAID <> d.PAID
   OR c.PENDING <> d.PENDING
   OR c.OUTSTANDING <> d.OUTSTANDING